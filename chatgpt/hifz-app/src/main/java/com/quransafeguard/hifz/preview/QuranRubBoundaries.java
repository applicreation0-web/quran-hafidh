    /** Global rub' index n, 1..240. */
    static int[] rowForIndex(int n) {
        if (n < 1 || n > 240) throw new IllegalArgumentException("invalid rub' index " + n);
        return TABLE[n - 1];
    }

    static int pageForRub(int hizb, int position) {
        if (hizb < 1 || hizb > 60) throw new IllegalArgumentException("invalid hizb " + hizb);
        if (position < 0 || position > 3) throw new IllegalArgumentException("invalid position " + position);
        return TABLE[(hizb - 1) * 4 + position][3];
    }

    /** The rub' boundary starting on this exact page, or null if none does — no two of the
     * 240 pages ever coincide, so this is always at most one match. */
    static int[] boundaryOnPage(int page) {
        for (int[] row : TABLE) if (row[3] == page) return row;
        return null;
    }

    /** Which rub' the given page currently falls within — the last boundary whose own
     * start page is not after it. TABLE is already in ascending page order (n order). */
    static int[] currentAt(int page) {
        int[] current = TABLE[0];
        for (int[] row : TABLE) {
            if (row[3] > page) break;
            current = row;
        }
        return current;
    }
